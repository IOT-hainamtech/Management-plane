"""Capabilities required by use cases; adapters implement them structurally."""

from contextlib import AbstractContextManager
from datetime import datetime
from typing import Protocol


class ConfigJobPort(Protocol):
    kind: str
    resource_key: str
    version: int
    payload: dict


class InboxEventPort(Protocol):
    event_id: str
    kind: str
    payload: dict


class FrappePort(Protocol):
    def all(self, doctype: str, filters: list | None = None) -> list[dict]: ...
    def find(self, doctype: str, field: str, value: str, filters: list | None = None) -> dict | None: ...
    def create(self, doctype: str, body: dict) -> dict: ...
    def update(self, doctype: str, name: str, body: dict) -> dict: ...


class DataPlanePort(Protocol):
    def send(self, kind: str, resource_key: str, payload: dict) -> dict: ...
    def latest(self, device_id: str) -> dict: ...
    def telemetry(self, device_id: str) -> dict: ...


class StorePort(Protocol):
    def cycle_lock(self) -> AbstractContextManager[bool]: ...
    def recover_processing(self) -> None: ...
    def stage_many(self, resources: list[tuple], batch_size: int = 100) -> dict: ...
    def claim_config(self) -> ConfigJobPort | None: ...
    def finish_config(self, kind: str, resource_key: str) -> None: ...
    def fail_config(self, job: ConfigJobPort, error: Exception, permanent: bool = False) -> None: ...
    def accept_event(self, event_id: str, kind: str, payload: dict) -> tuple[str, bool]: ...
    def claim_inbox(self) -> InboxEventPort | None: ...
    def finish_inbox(self, event_id: str) -> None: ...
    def fail_inbox(self, event: InboxEventPort, error: Exception, permanent: bool = False) -> None: ...
    def status_is_stale(self, org_code: str, device_id: str, state_at: datetime) -> bool: ...
    def save_status_cursor(self, org_code: str, device_id: str, state: str, state_at: datetime) -> None: ...
